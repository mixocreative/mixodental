// Regenerates src/fonts.css from the @fontsource packages: woff2 only, unicode-range split, files referenced
// from node_modules.
//
// TWO faces, and only two: the Latin ones. Atkinson Hyperlegible Next carries every Latin word and every number
// (it is drawn for legibility: 0 and O, 1 and l, and the other pairs a reader can mix up stay apart), and
// Noto Serif carries the title. Both are bundled, so the part of the interface that is the same in every
// language looks the same on every machine.
//
// Kana, kanji and Chinese characters come from the READER'S OWN MACHINE. Every CJK face worth having is tens of
// megabytes, and a dental clinic's machine already has a good one; the stacks in src/styles/theme.css name the
// platform faces in order, Japanese and Traditional Chinese separately, because their kanji forms differ.
//
// Each file is split by unicode-range, so a browser fetches only the few subsets the words on screen need. The
// order a word picks a face is the font-family stack of the theme, not the order here.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FAMILIES = [
  // Headers, content and every number, in three weights.
  { pkg: 'atkinson-hyperlegible-next', weights: [400, 500, 700], note: 'Atkinson Hyperlegible Next, SIL OFL 1.1' },
  // The title, which is the one place a serif is used. Noto Serif is the SAME TYPE FAMILY as the Noto Serif TC
  // and Noto Serif JP the CJK stacks name, so a title is one face in all three languages instead of three
  // unrelated ones - and it is drawn at every weight, so a heavy title is a real bold and not a browser
  // smearing a single weight sideways. Only the `latin` subset (its `latin-ext` alone is 128 KB for accented letters no heading contains): the rest of what the package carries (Cyrillic,
  // Greek, Vietnamese, maths) is weight in `dist` that this app can never show.
  { pkg: 'noto-serif', weights: [400, 800], subsets: ['latin'], note: 'Noto Serif, SIL OFL 1.1' },
];

const out = [`/* Generated by scripts/gen-fonts-css.mjs. ${FAMILIES.map((family) => family.note).join('; ')} (see THIRD-PARTY-NOTICES.txt). */`];
for (const { pkg, weights, subsets } of FAMILIES) {
  const dir = join(root, 'node_modules', '@fontsource', pkg);
  for (const weight of weights) {
    // Without `subsets` the weight's whole file is taken, which is every subset the package carries.
    const sources = (subsets ?? [null]).map((subset) => readFileSync(join(dir, subset ? `${subset}-${weight}.css` : `${weight}.css`), 'utf8'));
    const faces = sources.flatMap((css) => css.match(/@font-face\s*\{[^}]*\}/g) ?? []);
    if (faces.length === 0) throw new Error(`no face in ${pkg} ${weight}`);
    for (const block of faces) {
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
      if (!file) throw new Error(`no woff2 in a ${pkg} ${weight} face`);
      out.push(block.replace(/src:[^;]+;/, `src: url(../node_modules/@fontsource/${pkg}/files/${file}) format('woff2');`));
    }
  }
}
writeFileSync(join(root, 'src', 'fonts.css'), out.join('\n') + '\n');
console.log(`src/fonts.css: ${out.length - 1} faces`);
