// Regenerates src/fonts.css from the @fontsource packages: woff2 only, unicode-range split, files referenced
// from node_modules.
//
// THE LATIN FACES are taken whole. Atkinson Hyperlegible Next carries every Latin word and every number (it is
// drawn for legibility: 0 and O, 1 and l, and the other pairs a reader can mix up stay apart), and Noto Serif
// carries the title.
//
// THE JAPANESE TITLE FACE is CUT DOWN TO THE WORDS THIS APP SAYS. A CJK face is tens of megabytes, which is why
// this app used to bundle none and leave kana and kanji to the reader's own machine - but that left the
// Japanese title at whatever weight the machine happened to have, and on a machine with no Japanese serif
// installed it fell through to a default with no bold at all. The Japanese here is a CLOSED SET: every word is
// in src/locales/ja.ts. So Noto Serif JP is subset to exactly the characters that file contains - around five
// hundred glyphs out of some seventeen thousand - which is tens of kilobytes, and the Japanese title is then
// the same face at the same weight on every machine. It is the Japanese sibling of the Noto Serif that draws
// the Latin, so the two languages are one family.
//
// Chinese is still the reader's own machine: `--font-title-zh` names the platform faces in order, and the
// Traditional Chinese kanji forms differ from the Japanese ones, so the two must never share a face.
//
// Each Latin file is split by unicode-range, so a browser fetches only the few subsets the words on screen
// need. The order a word picks a face is the font-family stack of the theme, not the order here.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FAMILIES = [
  // Headers, content and every number, in three weights.
  { pkg: 'atkinson-hyperlegible-next', weights: [400, 500, 700], note: 'Atkinson Hyperlegible Next, SIL OFL 1.1' },
  // The title, which is the one place a serif is used. Noto Serif is drawn at every weight, so a heavy title is
  // a real bold and not a browser smearing a single weight sideways. Only the `latin` subset: its `latin-ext`
  // alone is 128 KB for accented letters no heading in these three languages contains, and the rest of what the
  // package carries (Cyrillic, Greek, Vietnamese, maths) this app can never show.
  { pkg: 'noto-serif', weights: [400, 800], subsets: ['latin'], note: 'Noto Serif, SIL OFL 1.1' },
  // EVERY NUMBER, and the Latin of every title. A mono face is drawn so each digit occupies the same width,
  // so a measurement that ticks does not shuffle the words beside it, and a column of them lines up without
  // asking for tabular figures. Latin only: it has no kana or kanji and is never asked for any.
  { pkg: 'roboto-mono', weights: [400, 700], subsets: ['latin'], note: 'Roboto Mono, Apache-2.0' },
];

/** The Japanese title face, cut to the characters src/locales/ja.ts contains. */
const JAPANESE = {
  pkg: 'noto-serif-jp',
  family: 'Noto Serif JP',
  weights: [400, 800],
  /** The package's own `japanese` subset is the whole Japanese glyph set; this cuts it down. */
  source: 'japanese',
  from: join('src', 'locales', 'ja.ts'),
  outDir: join('src', 'assets', 'fonts'),
  note: 'Noto Serif JP, SIL OFL 1.1 (subset to this app\'s Japanese)',
};

const notes = [...FAMILIES.map((family) => family.note), JAPANESE.note];
const out = [`/* Generated by scripts/gen-fonts-css.mjs. ${notes.join('; ')} (see THIRD-PARTY-NOTICES.txt). */`];

for (const { pkg, weights, subsets } of FAMILIES) {
  const dir = join(root, 'node_modules', '@fontsource', pkg);
  for (const weight of weights) {
    // Without `subsets` the weight's whole file is taken, which is every subset the package carries.
    const sources = (subsets ?? [null]).map((subset) => readFileSync(join(dir, subset ? `${subset}-${weight}.css` : `${weight}.css`), 'utf8'));
    const faces = sources.flatMap((css) => css.match(/@font-face\s*\{[^}]*\}/g) ?? []);
    if (faces.length === 0) throw new Error(`no face in ${pkg} ${weight}`);
    for (const block of faces) {
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
      if (!file) throw new Error(`no woff2 in a ${pkg} ${weight} face`);
      out.push(block.replace(/src:[^;]+;/, `src: url(../node_modules/@fontsource/${pkg}/files/${file}) format('woff2');`));
    }
  }
}

// Every character the Japanese locale holds. The file's keys are English and its values are the Japanese, and
// taking the WHOLE FILE is deliberate: a key, a comment or a punctuation mark costs one glyph and cannot be
// forgotten, where picking the values apart could miss one and leave a hole in a word.
const japaneseText = readFileSync(join(root, JAPANESE.from), 'utf8');
const wanted = [...new Set(japaneseText)].sort().join('');
mkdirSync(join(root, JAPANESE.outDir), { recursive: true });
let subsetBytes = 0;
for (const weight of JAPANESE.weights) {
  const file = `${JAPANESE.pkg}-${JAPANESE.source}-${weight}-normal.woff2`;
  const whole = readFileSync(join(root, 'node_modules', '@fontsource', JAPANESE.pkg, 'files', file));
  const cut = await subsetFont(whole, wanted, { targetFormat: 'woff2' });
  const name = `noto-serif-jp-ui-${weight}.woff2`;
  writeFileSync(join(root, JAPANESE.outDir, name), cut);
  subsetBytes += cut.length;
  out.push(`@font-face {
  font-family: '${JAPANESE.family}';
  font-style: normal;
  font-display: swap;
  font-weight: ${weight};
  src: url(./assets/fonts/${name}) format('woff2');
}`);
  console.log(`  ${name}: ${(whole.length / 1024 / 1024).toFixed(2)} MB -> ${(cut.length / 1024).toFixed(1)} kB`);
}

// What went into the subset, recorded so a test can hold the app to it: a Japanese string added later with a
// character this file does not list would fall out of the bundled face and be drawn by whatever the machine
// has, in the middle of a word. `japaneseSubset.test.ts` fails instead, and says to run `npm run fonts`.
writeFileSync(join(root, JAPANESE.outDir, 'japanese-subset.txt'), wanted);

writeFileSync(join(root, 'src', 'fonts.css'), out.join('\n') + '\n');
console.log(`src/fonts.css: ${out.length - 1} faces; Japanese subset ${[...wanted].length} characters, ${(subsetBytes / 1024).toFixed(1)} kB`);
