// Regenerates src/fonts.css from the @fontsource packages: woff2 only, unicode-range split, files referenced
// from node_modules.
//
// Six faces, one for every cell of language x style (docs/ui-styling.md "The three text styles"). The app loads
// these and nothing else: a stack names its Latin face, its CJK face and a generic, never a platform font, so a
// screen looks the same on every machine.
//
//              sans (headers, content, numbers)   serif (the title)
//   Latin      Atkinson Hyperlegible Next         Instrument Serif
//   Japanese   Zen Kaku Gothic New                Shippori Mincho B1
//   Chinese    Noto Sans TC                       Noto Serif TC
//
// Atkinson is drawn for legibility (0 and O, 1 and l, and the other pairs a reader can mix up stay apart) and is
// the Latin face of all three languages; the CJK face behind it draws kana, kanji and Chinese characters. The two
// serifs carry titles only, so they need one weight. Every file is split by unicode-range, so a browser fetches
// only the few subsets the words on screen actually need. The order a word picks a face is the font-family stack
// of the theme (src/styles/theme.css), not the order here.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TEXT = [400, 500, 700];
const TITLE = [400];
const FAMILIES = [
  { pkg: 'atkinson-hyperlegible-next', weights: TEXT, note: 'Atkinson Hyperlegible Next, SIL OFL 1.1' },
  { pkg: 'instrument-serif', weights: TITLE, note: 'Instrument Serif, SIL OFL 1.1' },
  { pkg: 'zen-kaku-gothic-new', weights: TEXT, note: 'Zen Kaku Gothic New, SIL OFL 1.1' },
  { pkg: 'shippori-mincho-b1', weights: TITLE, note: 'Shippori Mincho B1, SIL OFL 1.1' },
  { pkg: 'noto-sans-tc', weights: TEXT, note: 'Noto Sans TC, SIL OFL 1.1' },
  { pkg: 'noto-serif-tc', weights: TITLE, note: 'Noto Serif TC, SIL OFL 1.1' },
];

const out = [`/* Generated by scripts/gen-fonts-css.mjs. ${FAMILIES.map((family) => family.note).join('; ')} (see THIRD-PARTY-NOTICES.txt). */`];
for (const { pkg, weights } of FAMILIES) {
  const dir = join(root, 'node_modules', '@fontsource', pkg);
  for (const weight of weights) {
    const css = readFileSync(join(dir, `${weight}.css`), 'utf8');
    const faces = css.match(/@font-face\s*\{[^}]*\}/g) ?? [];
    if (faces.length === 0) throw new Error(`no face in ${pkg} ${weight}`);
    for (const block of faces) {
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
      if (!file) throw new Error(`no woff2 in a ${pkg} ${weight} face`);
      out.push(block.replace(/src:[^;]+;/, `src: url(../node_modules/@fontsource/${pkg}/files/${file}) format('woff2');`));
    }
  }
}
writeFileSync(join(root, 'src', 'fonts.css'), out.join('\n') + '\n');
console.log(`src/fonts.css: ${out.length - 1} faces`);
