// Regenerates src/fonts.css from the @fontsource packages: woff2 only, unicode-range split, weights 400/500/700,
// files referenced from node_modules.
//
// Three faces. Atkinson Hyperlegible Next carries the Latin alphabet of every header and every line of content
// (it is drawn for legibility: 0 and O, 1 and l, and the other pairs a reader can mix up are told apart). Zen Kaku
// Gothic New carries kana and kanji, and is the fallback for everything Atkinson has no glyph for. Instrument Serif
// is the display face, used by the large title and nowhere else, so it needs one weight. The order in which a word
// picks a face is the font-family stack of the theme (src/styles/theme.css), not the order here.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FAMILIES = [
  { pkg: 'instrument-serif', weights: [400], note: 'Instrument Serif, SIL OFL 1.1' },
  { pkg: 'atkinson-hyperlegible-next', weights: [400, 500, 700], note: 'Atkinson Hyperlegible Next, SIL OFL 1.1' },
  { pkg: 'zen-kaku-gothic-new', weights: [400, 500, 700], note: 'Zen Kaku Gothic New, SIL OFL 1.1' },
];

const out = [`/* Generated by scripts/gen-fonts-css.mjs. ${FAMILIES.map((family) => family.note).join('; ')} (see THIRD-PARTY-NOTICES.txt). */`];
for (const { pkg, weights } of FAMILIES) {
  const dir = join(root, 'node_modules', '@fontsource', pkg);
  for (const weight of weights) {
    const css = readFileSync(join(dir, `${weight}.css`), 'utf8');
    const faces = css.match(/@font-face\s*\{[^}]*\}/g) ?? [];
    if (faces.length === 0) throw new Error(`no face in ${pkg} ${weight}`);
    for (const block of faces) {
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
      if (!file) throw new Error(`no woff2 in a ${pkg} ${weight} face`);
      out.push(block.replace(/src:[^;]+;/, `src: url(../node_modules/@fontsource/${pkg}/files/${file}) format('woff2');`));
    }
  }
}
writeFileSync(join(root, 'src', 'fonts.css'), out.join('\n') + '\n');
console.log(`src/fonts.css: ${out.length - 1} faces`);
